"""Merge the three literature-search tracks into inventory/papers.tsv and inventory/datasets.tsv.

Usage: python scripts/01_merge_inventory.py

Inputs (inventory/): search_track1_subcortical.tsv, search_track2_cortex_multiregion.tsv,
search_track3_spatial_atac.tsv, local_datasets.tsv.
Rows describing the same paper are merged field by field: the first informative value wins, in the order
track1 > track3 > track2 (track1/3 read most full texts); notes are concatenated with the track tag.
Screening decisions, shared cohorts and dataset tiers are curated below with the reason for each.
"""
from pathlib import Path
import re
import pandas as pd

INV = Path(__file__).resolve().parents[1] / "inventory"
TRACKS = [("t1", "search_track1_subcortical.tsv"), ("t3", "search_track3_spatial_atac.tsv"),
          ("t2", "search_track2_cortex_multiregion.tsv")]
ALIASES = {"nm2024": "prashant2024"}
UNINFORMATIVE = re.compile(r"^(na|nan|unknown|)$|not extracted|not specified|not found", re.I)

# Screening. include = claims extracted and (if data exist) used as comparator.
# R1 decisions (user, 2026-10-22): review entries resolved as recommended in R1.
EXCLUDE = {
    "zheng2026": "abstract only; probable reanalysis of public SN data (R1 decision)",
    "tuddenham2024": "PD donors not confirmed (R1 decision)",
    "hobson2026": "mostly AD; leptomeningeal immune cells (R1 decision)",
    "asapcrn2025": "umbrella data resource, not a paper (R1 decision)",
    "agarwal2020": "no PD donors (control reference atlas)",
    "corces2020": "no PD donors (cognitively healthy only)",
    "weber2024": "no PD donors (neurotypical locus coeruleus)",
    "aguila2021": "not single-cell (pooled LCM-seq)",
    "bathe2024": "not single-cell (ROI-level protein panels); PD status of 'pure LBD' unclear",
}
REVIEW = {
    "pecoraro2025": "include if its data contain PD donors (not downloaded yet)",
    "graf2025": "catalogue only: no data deposited, no controls described (R1 decision)",
    "chatila2023": "catalogue only: no data released (R1 decision)",
    "kim2026": "data source (AMP-PD vs PD5D) to verify",
    "corces2026": "merged into menon2026 (same Banner multiome data; R1 decision)",
}
# Papers that analyse data generated by another inventory entry (no new single-cell data).
REUSE = {"clarence2025": "prashant2024", "lin2026": "PD5D + public cohorts", "fullard2025": "lee2026 (PsychAD)",
         "shwab2025": "shwab2024", "shwab2025b": "shwab2024", "zheng2026": "public SN data",
         "corces2026": "menon2026"}
# Shared donor cohorts: one dataset row per cohort (and modality family) in datasets.tsv.
COHORT = {
    "prashant2024": "AMP-PD multiregion", "clarence2025": "AMP-PD multiregion",
    "lee2026": "PsychAD DLPFC", "fullard2025": "PsychAD DLPFC",
    "lin2026": "PD5D (Scherzer)", "parker2026": "PD5D (Scherzer)", "scherzer2026": "PD5D (Scherzer)",
    "kim2026": "PD5D (Scherzer)",
    "barbareyes2025": "MGH striatum (Barba-Reyes)", "barbareyes2026": "MGH striatum (Barba-Reyes)",
    "shwab2024": "Duke temporal cortex (Shwab)", "shwab2025": "Duke temporal cortex (Shwab)",
    "shwab2025b": "Duke temporal cortex (Shwab)",
    "menon2026": "Banner multiome 5-region (Corces)", "corces2026": "Banner multiome 5-region (Corces)",
    "garza2026": "Lund/ASAP Jakobsson", "graziano2025": "Lund/ASAP Jakobsson",
    "ma2025": "Columbia (Sulzer)", "ma2026": "Columbia (Sulzer)",
}
# Comparator tier (overrides the automatic rule in tier()).
TIER_OVERRIDE = {
    "prashant2024": ("A", "processed counts open on CELLxGENE"),
    "lee2026": ("A", "processed counts open on CELLxGENE (PsychAD; PD subset)"),
    "adams2024": ("A", "processed multiome open on GEO"),
    "menon2026": ("A", "local copy (CELLxGENE)"),
    "sigalova2026": ("B", "counts only on ASAP CRN Cloud (open Zenodo 19034709 holds metadata/peaks only)"),
    "barbareyes2026": ("A", "own data (local)"),
    "kamath2022": ("A", "local copy; Slide-seq on controls only"),
    "shin2025": ("D", "2 PD / 2 control ROI-level GeoMx: too small for donor-level tests"),
    "goralski2024": ("C", "within-donor LB+ vs LB- neurons, no controls"),
    "yoo2024": ("B", "Korean archive (KRA) access; 4 PD / 4 control"),
}

COLS = ["paper_id", "first_author", "year", "title", "journal_or_preprint", "doi", "pmid", "modality",
        "regions", "n_pd", "n_ctrl", "n_other_disease", "n_nuclei", "accession", "data_access",
        "processed_data_available", "author_cell_labels_available", "main_conclusions_short", "notes"]


def informative(v):
    return isinstance(v, str) and not UNINFORMATIVE.search(v.strip())


def merge_tracks():
    rows = {}
    for tag, fn in TRACKS:
        df = pd.read_csv(INV / fn, sep="\t", dtype=str, keep_default_na=False)
        for r in df.to_dict("records"):
            pid = ALIASES.get(r["paper_id"].strip(), r["paper_id"].strip())
            r["paper_id"] = pid
            if pid not in rows:
                rows[pid] = {c: "" for c in COLS} | {"paper_id": pid, "tracks": "", "notes": ""}
            m = rows[pid]
            m["tracks"] = ";".join(filter(None, [m["tracks"], tag]))
            for c in COLS[1:-1]:
                if not informative(m[c]) and informative(r.get(c, "")):
                    m[c] = r[c].strip()
            if informative(r.get("notes", "")):
                m["notes"] = " | ".join(filter(None, [m["notes"], f"[{tag}] {r['notes'].strip()}"]))
    return pd.DataFrame(rows.values())


def first_int(v):
    m = re.search(r"\d+", v or "")
    return int(m.group()) if m else None


def tier(r):
    if r["paper_id"] in TIER_OVERRIDE:
        return TIER_OVERRIDE[r["paper_id"]]
    mod, acc = r["modality"].lower(), r["data_access"].lower()
    rna = bool(re.search(r"snrna|scrna|multiome", mod))
    npd, nct = first_int(r["n_pd"]), first_int(r["n_ctrl"])
    if not rna:
        return ("C", "spatial / ATAC / imaging only")
    if npd is not None and nct is not None and min(npd, nct) < 3:
        return ("D", "fewer than 3 donors in a group")
    if acc.startswith("open") or "open (" in acc:
        return ("A", "open processed data")
    if "controlled" in acc:
        return ("B", "controlled access: needs application")
    return ("D", "no data route found")


def main():
    p = merge_tracks()
    p["screening"] = "include"
    p["screening_reason"] = ""
    for k, v in REVIEW.items():
        p.loc[p.paper_id == k, ["screening", "screening_reason"]] = ["review", v]
    for k, v in EXCLUDE.items():
        p.loc[p.paper_id == k, ["screening", "screening_reason"]] = ["exclude", v]
    p["reuses_data_of"] = p.paper_id.map(REUSE).fillna("")
    p["cohort"] = p.paper_id.map(COHORT).fillna(p.paper_id)
    local = pd.read_csv(INV / "local_datasets.tsv", sep="\t", dtype=str)
    p["local"] = p.paper_id.isin(local.paper_id).map({True: "yes", False: "no"})
    p.loc[p.paper_id.isin(["prashant2024", "clarence2025"]), "local"] = "yes"  # Fullard/Prashant object local
    t = p.apply(tier, axis=1, result_type="expand")
    p["comparator_tier"], p["tier_reason"] = t[0], t[1]
    p.loc[(p.screening == "exclude") | (p.reuses_data_of != ""), ["comparator_tier", "tier_reason"]] = ["-", "no own data"]
    p.loc[p.paper_id == "asapcrn2025", ["comparator_tier", "tier_reason"]] = ["-", "umbrella resource"]
    p = p.sort_values(["screening", "year", "paper_id"])
    p.to_csv(INV / "papers.tsv", sep="\t", index=False)

    # One dataset per cohort, from the papers that generated data.
    gen = p[(p.screening != "exclude") & (p.comparator_tier != "-")]
    ds = (gen.groupby("cohort")
          .agg(papers=("paper_id", ";".join), regions=("regions", "first"), modality=("modality", " + ".join),
               n_pd=("n_pd", "first"), n_ctrl=("n_ctrl", "first"), accession=("accession", " | ".join),
               data_access=("data_access", "first"), local=("local", "max"),
               comparator_tier=("comparator_tier", "min"), tier_reason=("tier_reason", "first"),
               screening=("screening", "min"))
          .reset_index().sort_values(["comparator_tier", "cohort"]))
    ds.to_csv(INV / "datasets.tsv", sep="\t", index=False)
    print(p.screening.value_counts().to_string(), "\n")
    print(ds.comparator_tier.value_counts().sort_index().to_string(), "\n")
    print(ds[["cohort", "comparator_tier", "local", "n_pd", "n_ctrl", "regions"]].to_string(max_colwidth=45))


if __name__ == "__main__":
    main()
